// =============================================================================
// execution_events.hpp -- the canonical execution events of an application run (D0.5, ADR-0030).
//
// TMR is the ONE producer of trainit_interfaces/ExecutionEvent: what the application DID, in its own
// vocabulary, on the relative topic `trainit/execution_events` of the runner's robot slot (ADR-0023),
// RELIABLE, VOLATILE, keep-last 100 -- a subscriber that joins later never receives an older event.
//
// ONE observer of the tree (a BT::StatusChangeLogger), never code in the nodes:
//   - a task is a `task_<name>` tree, entered through a SubTree node: TASK_ENTERED / TASK_EXITED with the
//     canonical task name, on every entry (a called or repeated task is entered again);
//   - a step is canonical when TSA gave it an id (D18): its node(s) run inside
//     <Sequence name="trainit_step:<id>:<kind>">, the ONLY node name read here: STEP_ENTERED / STEP_EXITED
//     with the step id and kind. A node without that name produces nothing;
//   - transitions: ENTERED = a node that is not active starts (-> RUNNING / SUCCESS / FAILURE: from IDLE, or
//     re-ticked from a finished status by a reactive parent); EXITED = -> SUCCESS (SUCCEEDED) or FAILURE (FAILED),
//     or RUNNING -> IDLE (HALTED: stopped by its parent). A start that completes at once is ENTERED then EXITED.
//     SKIPPED and the resets to IDLE of finished nodes produce nothing (a step skipped by a `_skipIf` -- never
//     generated by TSA -- would stay open until its parent resets it, then end HALTED);
//   - a process event, when the process controller DISPATCHED it (ObservedProcessController): PROCESS_EVENT
//     with the logical channel, kind and value, and the innermost active task / identified step;
//   - a grasp step: attempt_index = its entries in this run (1, 2, ... under a retry), and the candidate
//     (ADR-0026 id / provider) its SetWaypointFromCandidate reads, when it is on the blackboard;
//   - RUN_STARTED before the first tick, RUN_ENDED after the last (with how the run ended). A run stopped by a
//     shutdown first closes every scope still open, innermost first (EXITED HALTED), then RUN_ENDED HALTED --
//     the runner calls runEnded from a PRE-shutdown callback, while the context can still publish. Nothing is
//     emitted after RUN_ENDED.
// Every event: the runner node's clock (ROS time, or sim time; 0 before the first /clock), the run id, seq = 1,
// 2, ... (the order of events sharing a stamp: assigned and published under one lock). Publishing is a
// non-blocking ROS publish; an error while observing or publishing is counted and dropped, never thrown into the
// tick: nothing here changes what the tree does, and nothing here records data.
// =============================================================================
